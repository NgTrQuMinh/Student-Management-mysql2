CREATE TABLE IF NOT EXISTS lop (
    id INT AUTO_INCREMENT PRIMARY KEY,
    ten_lop VARCHAR(255) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sinhvien (
    id INT AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    ma_sv VARCHAR(50) UNIQUE,
    ho_ten VARCHAR(255) NOT NULL,
    email VARCHAR(255) UNIQUE,
    lop_id INT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (lop_id) REFERENCES lop(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS monhoc (
    id INT AUTO_INCREMENT PRIMARY KEY,
    ma_mon VARCHAR(50) UNIQUE,
    ten_mon VARCHAR(255) NOT NULL,
    so_tin_chi INT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS diem (
    id INT AUTO_INCREMENT PRIMARY KEY,
    sinhvien_id INT,
    monhoc_id INT,
    diem DECIMAL(5, 2),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (sinhvien_id) REFERENCES sinhvien(id) ON DELETE CASCADE,
    FOREIGN KEY (monhoc_id) REFERENCES monhoc(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS nguoidung (
    id INT AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);